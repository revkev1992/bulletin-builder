const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('bb', {
  loadWeek: (file) => ipcRenderer.invoke('week:load', file),
  chooseWeek: () => ipcRenderer.invoke('week:choose'),
  newWeekFrom: (file) => ipcRenderer.invoke('week:new-from', file),
  recentWeeks: (file) => ipcRenderer.invoke('weeks:recent', file),
  describeWeek: (file) => ipcRenderer.invoke('week:describe', file),
  createWeek: (src, name, from) => ipcRenderer.invoke('week:create', src, name, from),
  newBlank: (nearFile, setup) => ipcRenderer.invoke('week:new-blank', nearFile, setup),
  saveAs: (file) => ipcRenderer.invoke('week:save-as', file),
  edit: (what) => ipcRenderer.invoke('edit:do', what),
  setStyles: (file, styles) => ipcRenderer.invoke('week:set-styles', file, styles),
  readStyles: (hint) => ipcRenderer.invoke('week:read-styles', hint),
  setPage: (file, setup) => ipcRenderer.invoke('week:set-page', file, setup),
  setScheme: (file, change) => ipcRenderer.invoke('week:set-scheme', file, change),
  windows: {
    open: (file) => ipcRenderer.invoke('win:new', file),
    list: () => ipcRenderer.invoke('win:list'),
    focus: (id) => ipcRenderer.invoke('win:focus', id),
    arrange: () => ipcRenderer.invoke('win:arrange'),
    cascade: () => ipcRenderer.invoke('win:cascade'),
  },
  renamePage: (file, n, name) => ipcRenderer.invoke('week:rename-page', file, n, name),
  exportPages: (file, opts) => ipcRenderer.invoke('week:export-pages', file, opts),
  pack: (file, info) => ipcRenderer.invoke('week:pack', file, info),
  readTextFile: () => ipcRenderer.invoke('file:read-text'),
  clipboardPicture: (weekFile) => ipcRenderer.invoke('clipboard:picture', weekFile),
  clipboardHasPicture: () => ipcRenderer.invoke('clipboard:has-picture'),
  openExternal: (url) => ipcRenderer.invoke('shell:open', url),
  onOpen: (fn) => ipcRenderer.on('week:open', (_e, file) => fn(file)),
  onZoom: (fn) => ipcRenderer.on('view:zoom', (_e, factor) => fn(factor)),
  onCommand: (fn) => ipcRenderer.on('cmd', (_e, name) => fn(name)),
  claim: (file, half, force) => ipcRenderer.invoke('session:claim', file, half, !!force),
  release: () => ipcRenderer.invoke('session:release'),
  save: (data) => ipcRenderer.invoke('session:save', data),
  setDirty: (flag) => ipcRenderer.send('doc:dirty', flag),
  closeWindow: () => ipcRenderer.send('app:close-window'),
  importPicture: (weekFile) => ipcRenderer.invoke('asset:import', weekFile),
  version: () => ipcRenderer.invoke('app:version'),
  pageOp: (file, half, op) => ipcRenderer.invoke('pages:op', file, half, op),
  recent: () => ipcRenderer.invoke('recent:list'),
  exportPdf: (file, paper) => ipcRenderer.invoke('week:export-pdf', file, paper),
  print: (file, paper) => ipcRenderer.invoke('week:print', file, paper),
  reveal: (p) => ipcRenderer.invoke('file:reveal', p),
  importPicturePath: (weekFile, src) => ipcRenderer.invoke('asset:import-path', weekFile, src),
  blocks: {
    list: (weekFile) => ipcRenderer.invoke('blocks:list', weekFile),
    add: (weekFile, opts) => ipcRenderer.invoke('blocks:add', weekFile, opts),
    rename: (weekFile, id, change) => ipcRenderer.invoke('blocks:rename', weekFile, id, change),
    remove: (weekFile, id) => ipcRenderer.invoke('blocks:remove', weekFile, id),
    use: (weekFile, id) => ipcRenderer.invoke('blocks:use', weekFile, id),
  },
  music: {
    list: (weekFile) => ipcRenderer.invoke('music:list', weekFile),
    add: (weekFile, opts) => ipcRenderer.invoke('music:add', weekFile, opts),
    update: (weekFile, id, change) => ipcRenderer.invoke('music:update', weekFile, id, change),
    remove: (weekFile, id) => ipcRenderer.invoke('music:remove', weekFile, id),
    use: (weekFile, id) => ipcRenderer.invoke('music:use', weekFile, id),
  },
});
